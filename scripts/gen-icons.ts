/**
 * Generates src/ui/components/icons.generated.ts: inline SVG path data for exactly the Material Symbols
 * the UI uses (Outlined, wght 400), replacing the 4 MB icon font. Add a name to ICONS and re-run.
 * Run: npm run gen:icons   (output is committed)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ICONS = [
  'arrow_back',
  'badge',
  'check',
  'chevron_right',
  'close',
  'compare_arrows',
  'content_copy',
  'edit',
  'error',
  'filter_alt',
  'info',
  'key',
  'login',
  'refresh',
  'search',
  'settings',
  'shield',
  'side_navigation',
  'target',
  'visibility',
];

/** Names the UI uses -> the svg-400 file that supplies them (renamed upstream). */
const ALIAS: Record<string, string> = { expand_more: 'keyboard_arrow_down', new_releases: 'release_alert' };
const ALIASED = Object.keys(ALIAS);
/** Hand-drawn icons not in the package (path data in the 0 -960 960 960 box). */
const CUSTOM: Record<string, string> = {
  spark: 'M480-840Q520-520 840-480Q520-440 480-120Q440-440 120-480Q440-520 480-840Z',
};

const require = createRequire(import.meta.url);
const dir = path.join(path.dirname(require.resolve('@material-symbols/svg-400/package.json')), 'outlined');
const pathOf = (file: string) => {
  const svg = readFileSync(path.join(dir, file), 'utf8');
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join('');
  if (!d) throw new Error(`no path in ${file}`);
  return d;
};

const entries: string[] = [];
for (const n of [...ICONS, ...ALIASED].sort()) {
  const f = ALIAS[n] ?? n;
  entries.push(`  ${n}: { outline: '${pathOf(`${f}.svg`)}', fill: '${pathOf(`${f}-fill.svg`)}' },`);
}
for (const [n, d] of Object.entries(CUSTOM)) entries.push(`  ${n}: { outline: '${d}', fill: '${d}' },`);
const body = entries.join('\n');

const out = `/* GENERATED by scripts/gen-icons.ts from @material-symbols/svg-400. Do not edit by hand. */
export const ICON_PATHS = {
${body}
} as const;
export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(fileURLToPath(new URL('../src/ui/components/icons.generated.ts', import.meta.url)), out);
console.log(`wrote ${entries.length} icons`);
