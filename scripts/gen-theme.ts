/**
 * Generates src/ui/theme/tokens.css (colour roles) from a seed colour.
 * Run: npm run gen:theme   (output is committed)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  Blend,
  DynamicColor,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities';

const SEED = '#1A73E8';
const RISK = { read: '#1E8E3E', write: '#F9AB00', admin: '#D93025' } as const;
const DARK_DESAT = 0.9; // risk hues ~10% less chroma in dark mode

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

const roleNames = [
  'background',
  'onBackground',
  'surface',
  'surfaceDim',
  'surfaceBright',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'onSurface',
  'surfaceVariant',
  'onSurfaceVariant',
  'inverseSurface',
  'inverseOnSurface',
  'outline',
  'outlineVariant',
  'shadow',
  'scrim',
  'surfaceTint',
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'inversePrimary',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
] as const;

function scheme(dark: boolean): string[] {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), dark, 0);
  const lines = roleNames.map((n) => {
    const dc = (MaterialDynamicColors as unknown as Record<string, DynamicColor>)[n];
    return `  --md-sys-color-${kebab(n)}: ${hexFromArgb(dc.getArgb(s))};`;
  });
  const seedArgb = argbFromHex(SEED);
  for (const [name, hex] of Object.entries(RISK)) {
    const harmonized = Blend.harmonize(argbFromHex(hex), seedArgb);
    const h = Hct.fromInt(harmonized);
    const chroma = dark ? h.chroma * DARK_DESAT : h.chroma;
    const p = TonalPalette.fromHueAndChroma(h.hue, chroma);
    const t = dark ? { c: 80, on: 20, cc: 30, occ: 90 } : { c: 40, on: 100, cc: 90, occ: 10 };
    lines.push(
      `  --md-custom-color-${name}: ${hexFromArgb(p.tone(t.c))};`,
      `  --md-custom-color-on-${name}: ${hexFromArgb(p.tone(t.on))};`,
      `  --md-custom-color-${name}-container: ${hexFromArgb(p.tone(t.cc))};`,
      `  --md-custom-color-on-${name}-container: ${hexFromArgb(p.tone(t.occ))};`,
    );
  }
  return lines;
}

const light = scheme(false).join('\n');
const dark = scheme(true).join('\n');

const css = `/* GENERATED by scripts/gen-theme.ts from seed ${SEED}. Do not edit by hand. */

:root {
  color-scheme: light dark;
${light}
}

@media (prefers-color-scheme: dark) {
  :root {
${dark.replace(/^/gm, '  ')}
  }
}

:root[data-theme='light'] {
  color-scheme: light;
${light}
}

:root[data-theme='dark'] {
  color-scheme: dark;
${dark}
}
`;

const out = fileURLToPath(new URL('../src/ui/theme/tokens.css', import.meta.url));
writeFileSync(out, css);
console.log(`wrote ${out}`);
