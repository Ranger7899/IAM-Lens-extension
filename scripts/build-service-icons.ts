// Builds the service -> official GCP icon assets (IAM-34). Zero dependencies; run with `node scripts/build-service-icons.ts`.
//  - reads every service prefix from data/roles.snapshot.json (permissions + `roles/<svc>.` role prefixes)
//  - resolves each through the hand-curated table in scripts/service-icon-map.ts
//  - copies only the icons in use into public/service-icons/ (flat, snake_case names)
//  - writes src/ui/serviceIcons.generated.ts (service -> extension asset path)
//  - prints coverage and warns about any of the 60 services with the most permissions lacking an exact icon
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { GENERIC, IAM_ICON, resolveServiceIcon, serviceOf, type Tier } from './service-icon-map.ts';

const root = path.resolve(import.meta.dirname, '..');
const VENDOR = path.join(root, 'vendor', 'gcp-icons');
const OUT_DIR = path.join(root, 'public', 'service-icons');
const GEN = path.join(root, 'src', 'ui', 'serviceIcons.generated.ts');
const TOP_N = 60;

interface Snapshot {
  permissions: string[];
  roles: { name: string }[];
}
const snap = JSON.parse(readFileSync(path.join(root, 'data', 'roles.snapshot.json'), 'utf8')) as Snapshot;

const counts = new Map<string, number>();
for (const p of snap.permissions) counts.set(serviceOf(p), (counts.get(serviceOf(p)) ?? 0) + 1);
for (const r of snap.roles) if (!counts.has(serviceOf(r.name))) counts.set(serviceOf(r.name), 0);

/** `core/BigQuery-512-color.svg` -> `bigquery-512-color.svg`; keeps the pack in the name to avoid collisions. */
const assetName = (src: string) => src.replace('/', '--').toLowerCase();

const services = [...counts.keys()].sort();
const mapping: Record<string, string> = {};
const tiers = new Map<Tier, string[]>([
  ['exact', []],
  ['category', []],
  ['generic', []],
]);
const used = new Set<string>([GENERIC, IAM_ICON]);
for (const svc of services) {
  const { file, tier } = resolveServiceIcon(svc);
  if (!existsSync(path.join(VENDOR, file))) throw new Error(`service "${svc}" maps to missing icon ${file}`);
  used.add(file);
  mapping[svc] = `/service-icons/${assetName(file)}`;
  tiers.get(tier)!.push(svc);
}

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
for (const file of [...used].sort())
  copyFileSync(path.join(VENDOR, file), path.join(OUT_DIR, assetName(file)));

const body = services.map((s) => `  ${JSON.stringify(s)}: ${JSON.stringify(mapping[s])},`).join('\n');
writeFileSync(
  GEN,
  `// GENERATED by scripts/build-service-icons.ts from scripts/service-icon-map.ts. Do not edit.
export const SERVICE_ICONS: Record<string, string> = {
${body}
};

export const GENERIC_ICON = ${JSON.stringify(`/service-icons/${assetName(GENERIC)}`)};
export const IAM_ICON = ${JSON.stringify(`/service-icons/${assetName(IAM_ICON)}`)};
`,
);

const total = services.length;
const pct = (n: number) => `${((n / total) * 100).toFixed(1)}%`;
console.log(
  `Service icons: ${total} services, ${used.size} distinct icons copied to public/service-icons/ (${readdirSync(OUT_DIR).length} files)`,
);
for (const [t, list] of tiers)
  console.log(`  ${t.padEnd(8)} ${String(list.length).padStart(4)}  ${pct(list.length)}`);
const top = [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, TOP_N);
const weak = top.filter(([s]) => resolveServiceIcon(s).tier !== 'exact').map(([s]) => s);
const topPerm = top.reduce((n, [, c]) => n + c, 0);
const allPerm = [...counts.values()].reduce((a, b) => a + b, 0);
console.log(
  `  top ${TOP_N} by permissions: ${TOP_N - weak.length} exact (${topPerm} of ${allPerm} permissions)`,
);
if (weak.length) {
  // The packs have no product icon for these; mapping them to a different product would mislead, so warn.
  console.warn(
    `WARN: top-${TOP_N} services without an exact product icon (category fallback): ${weak.join(', ')}`,
  );
}
